<?php
declare(strict_types=1);
namespace SanePhonics\Examples;

/**
 * Keep generated maps on the same authoring format as hand-edited Tiled projects.
 * @param array $data Generated map, world, or tileset document.
 * @return array Document with typed system lists and nested spawn components.
 */
function authoredMap(array $data): array
{
	$data = authoredEntities($data);

	$type = $data['type'] ?? '';

	if(!in_array($type, ['map', 'world'], true)) return $data;

	$properties = $data['properties'] ?? [];
	$found = false;

	foreach($properties as &$property)
	{
		if(!in_array($property['name'], ['phonics.systems', 'phonics.modules'], true)) continue;

		if($property['name'] === 'phonics.systems') $found = true;

		if($property['type'] !== 'string') continue;

		$list = json_decode($property['value'], true, 512, JSON_THROW_ON_ERROR);

		if(array_filter($list, /** Detect bindings that must retain their legacy option records.
		 * @param mixed $value System binding or reference.
		 * @return bool Whether the value cannot be represented as a string item.
		 */ static fn($value): bool => !is_string($value)
		)) continue;

		$property['type'] = 'list';

		$property['value'] = array_map(
			/** Encode one native Tiled string-list item.
		 * @param string $value System reference.
		 * @return array Typed list item.
		 */ static fn(string $value): array => [
			 'type' => 'string'
			 , 'value' => $value
		 ]
			, $list
		);
	}

	unset($property);

	if(!$found)
	$properties[] = [
		'name' => 'phonics.systems'
		, 'type' => 'list'
		, 'value' => [['type' => 'string', 'value' => $type === 'world' ? '@sane/spatial-maps' : '@sane/demo-map']]
	];

	$data['properties'] = $properties;

	/** Migrate spawn markers within recursively nested object layers.
	 * @param array $layers Authored layers at this depth.
	 * @return array Layers preserving geometry and unrelated properties.
	 */
	$visit = static function(array $layers) use (&$visit): array {
		foreach($layers as &$layer)
		{
			if(isset($layer['layers'])) $layer['layers'] = $visit($layer['layers']);

			foreach($layer['objects'] ?? [] as $index => $object)
			{
				if(($object['class'] ?? $object['type'] ?? '') !== 'Player') continue;

				unset($object['class']);
				$object['type'] = '';
				$object['properties'][] = [
					'name' => 'SpawnPoint'
					, 'type' => 'class'
					, 'propertytype' => 'SanePhonics.SpawnPoint'
					, 'value' => new \stdClass
				];

				$layer['objects'][$index] = $object;
			}
		}

		unset($layer);

		return $layers;
	};

	if(isset($data['layers'])) $data['layers'] = $visit($data['layers']);

	return $data;
}

/**
 * Move legacy feature fields into the appropriate typed settings without changing geometry.
 * @param array $data Map, tileset, or layer document generated by a course builder.
 * @return array Document using concrete entity presets and independent nested values.
 */
function authoredEntities(array $data): array
{
	static $classes;

	$classes ??= array_column(
		json_decode(
			file_get_contents(__DIR__ . '/../worlds/phonics.classes.json')
			, true
			, flags: JSON_THROW_ON_ERROR
		)['classes']
		, null
		, 'name'
	);

	foreach(['objects', 'tiles'] as $collection)
	foreach($data[$collection] ?? [] as $index => $object)
	{
		foreach($object['properties'] ?? [] as $key => $property)
		if(($property['type'] ?? '') === 'class' && $property['value'] === [])
		$object['properties'][$key]['value'] = new \stdClass;

		if(($object['class'] ?? null) === '' && str_starts_with($object['type'] ?? '', 'SanePhonics.Entity.'))
		unset($object['type']);

		$data[$collection][$index] = $object;
		$type = ($object['class'] ?? '') ?: ($object['type'] ?? '');

		if(str_starts_with($type, 'SanePhonics.Entity.')) $type = substr($type, strlen('SanePhonics.Entity.'));

		if($type === 'text-actor') $type = 'TextActor';

		$preset = 'SanePhonics.Entity.' . $type;

		if(!isset($classes[$preset])) continue;

		$properties = array_column($object['properties'] ?? [], null, 'name');
		$nested = [];

		foreach($classes[$preset]['members'] as $member)
		{
			$values = (array)($properties[$member['name']]['value'] ?? []);
			unset($properties[$member['name']]);

			foreach($classes[$member['propertyType']]['members'] as $field)
			{
				$key = ($type === 'ring' ? 'ring.' : '') . $field['name'];

				if(!isset($properties[$key])) continue;

				$values[$field['name']] = $properties[$key]['value'];
				unset($properties[$key]);
			}

			foreach($classes[$member['propertyType']]['members'] as $field)
			if($field['type'] === 'color' && isset($values[$field['name']]))
			{
				$color = strtolower($values[$field['name']]);
				$values[$field['name']] = strlen($color) === 7 ? '#ff' . substr($color, 1) : $color;
			}

			$nested[] = [
				'name' => $member['name']
				, 'type' => 'class'
				, 'propertytype' => $member['propertyType']
				, 'value' => $values ?: new \stdClass
			];
		}

		unset($object['class']);
		$object['type'] = $preset;
		$object['properties'] = [...array_values($properties), ...$nested];
		$data[$collection][$index] = $object;
	}

	foreach($data['layers'] ?? [] as $index => $layer) $data['layers'][$index] = authoredEntities($layer);

	return $data;
}
